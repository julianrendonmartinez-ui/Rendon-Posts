function qrPath(matrix) {
  const n = matrix.length;
  const partes = [];
  for (let y = 0; y < n; y++) {
    let x = 0;
    while (x < n) {
      if (matrix[y][x] === '1') {
        const x0 = x;
        while (x < n && matrix[y][x] === '1') x++;
        partes.push('M' + x0 + ' ' + y + 'h' + (x - x0) + 'v1h-' + (x - x0) + 'z');
      } else {
        x++;
      }
    }
  }
  return partes.join('');
}

